-- 05. Заказы с именами покупателей
-- JOIN (он же INNER JOIN) соединяет строки двух таблиц по условию ON
-- и оставляет только те, для которых пара нашлась.
-- Поэтому заказ 11 с несуществующим покупателем 99 в результат не попадёт.
-- o и c — короткие псевдонимы таблиц
SELECT o.id, c.name, o.status
FROM orders AS o
JOIN customers AS c ON c.id = o.customer_id
ORDER BY o.id;
